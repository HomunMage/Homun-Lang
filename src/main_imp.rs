/// Return the compiler version string (set at build time via HOMUN_VERSION env).
pub fn homunc_version() -> String {
    env!("HOMUN_VERSION").to_string()
}

/// Emit the embedded runtime to stdout, for `--emit-runtime > src/runtime.rs`.
///
/// `extras` names the optional hom-std modules to append. The default is none:
/// `builtin` plus `std` is what a module compiled with `--module` needs, and it
/// is the only combination that is both self-contained and free of duplicate
/// definitions. `chars` and `str_ext` redefine `is_alpha` / `is_digit` /
/// `is_alnum` / `is_upper` with different semantics from `std/str.rs`, and `re`
/// pulls in `use regex::Regex`, which the consuming crate would have to depend
/// on. Ask for those explicitly with `--with NAME`.
///
/// No inner attributes are emitted: the output is a fragment to `include!`, and
/// `#![..]` is only legal at the very top of a file.
pub fn emit_runtime_with(extras: Vec<String>) {
    println!("// Generated by homunc — Homun to Rust compiler");
    println!("// Runtime fragment: include! this, do not compile it as a file.");
    println!();
    println!("// ── builtin ────────────────────────────────────────────────");
    println!("{}", builtin_rs());
    if let Some(content) = embedded_rs("std") {
        println!("{}", content);
    }
    for name in &extras {
        match embedded_rs(name) {
            Some(content) => println!("{}", content),
            None => eprintln!("homunc: unknown runtime module `{name}`"),
        }
    }
}

/// Back-compatible entry point: the default set, no extras.
pub fn emit_runtime_fn() {
    emit_runtime_with(Vec::new())
}

/// Read a file to a String. Exits on I/O error.
pub fn read_file(path: String) -> String {
    std::fs::read_to_string(&path).unwrap_or_else(|e| {
        eprintln!("Cannot read {}: {}", path, e);
        std::process::exit(1);
    })
}

/// Extract the Ok value from a Result<String, String>.
/// On Err, prints the error to stderr and exits with code 1.
pub fn result_ok_or_exit(result: Result<String, String>) -> String {
    match result {
        Ok(s) => s,
        Err(e) => {
            eprintln!("{}", e);
            std::process::exit(1);
        }
    }
}

